"""
Step 2 - SQL KPI analysis.

Loads the clean data into a local SQLite database (data/tickets.db) and runs
every query in sql/kpi_queries.sql, saving the results to
reports/sql_results.md so they render nicely on GitHub.

Run:  python src/sql_analysis.py
"""
from __future__ import annotations

import re
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CLEAN = ROOT / "data" / "processed" / "tickets_clean.csv"
DB = ROOT / "data" / "tickets.db"
SQL_FILE = ROOT / "sql" / "kpi_queries.sql"
OUT = ROOT / "reports" / "sql_results.md"


def load_queries(path: Path) -> list[tuple[str, str]]:
    text = path.read_text()
    parts = re.split(r"^-- name:\s*(.+)$", text, flags=re.M)
    # parts = [preamble, name1, body1, name2, body2, ...]
    return [(parts[i].strip(), parts[i + 1].strip()) for i in range(1, len(parts), 2)]


def main() -> dict[str, pd.DataFrame]:
    df = pd.read_csv(CLEAN)
    with sqlite3.connect(DB) as con:
        df.to_sql("tickets", con, if_exists="replace", index=False)
        results = {name: pd.read_sql_query(sql, con) for name, sql in load_queries(SQL_FILE)}

    lines = ["# SQL Analysis Results\n",
             "Generated by `src/sql_analysis.py` from `sql/kpi_queries.sql`.\n"]
    for name, res in results.items():
        lines += [f"## {name}\n", res.to_markdown(index=False), ""]
        print(f"\n== {name} ==\n{res.to_string(index=False)}")
    OUT.write_text("\n".join(lines))
    return results


if __name__ == "__main__":
    main()
